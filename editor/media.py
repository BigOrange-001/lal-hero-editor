"""Bounded, non-destructive Pillow transformations for author-supplied images.

All rectangles use oriented source pixels (left, top, right, bottom). Output
is a single 8-bit RGBA PNG accepted by Mod API 1; source files are never changed.
"""
from __future__ import annotations

from io import BytesIO
from pathlib import Path
from functools import lru_cache
import json
import math
import sys
import warnings

from PIL import Image, ImageChops, ImageOps, UnidentifiedImageError
from PIL.PngImagePlugin import PngInfo

_SERVER = Path(__file__).resolve().parents[1] / "server"
if str(_SERVER) not in sys.path:
    sys.path.insert(0, str(_SERVER))
from mod_packages import validate_media
from mod_schema import LIMITS

MAX_SOURCE_BYTES = 64 * 1024 * 1024
MAX_SOURCE_PIXELS = 64_000_000
MAX_OUTPUT_SIDE = LIMITS["imageDimension"]
SLOT_SIZES = {"portrait": (320, 480), "icon": (160, 160), "skill": (128, 128), "preview": (640, 960)}
# Measured from original hero_A/B/C SWF character bounds (1 twip = 1/20 px).
PORTRAIT_SIZES = {2: (200, 200), 3: (300, 225), 4: (400, 250), 5: (500, 275), 6: (600, 300)}


def portrait_size(quality):
    if type(quality) is not int or quality not in PORTRAIT_SIZES:
        raise ValueError('立绘品质必须为白、绿、蓝、紫或橙。')
    return PORTRAIT_SIZES[quality]


def make_portrait(data, quality=6, box=None):
    """Fit the complete selection on the native quality canvas without stretching."""
    size = portrait_size(quality)
    image, _ = _open(data)
    try:
        selected = _box(image, box or (0, 0, image.width, image.height))
        try:
            fitted = ImageOps.contain(selected, size, Image.Resampling.LANCZOS)
            try:
                canvas = Image.new('RGBA', size, (0, 0, 0, 0))
                try:
                    canvas.alpha_composite(fitted, ((size[0]-fitted.width)//2, size[1]-fitted.height))
                    return _png(canvas)
                finally:
                    canvas.close()
            finally:
                fitted.close()
        finally:
            selected.close()
    finally:
        image.close()


QUALITY_LABELS = {2: "白", 3: "绿", 4: "蓝", 5: "紫", 6: "橙"}
QUALITY_COLORS = {2: "#c8ced7", 3: "#56b87b", 4: "#5b9de8", 5: "#b07be8", 6: "#efa64c"}
FRAME_ROOT = Path(__file__).resolve().parent / "resources/frames"


def _size(value):
    if (not isinstance(value, (list, tuple)) or len(value) != 2
            or any(type(part) is not int or not 1 <= part <= MAX_OUTPUT_SIDE for part in value)):
        raise ValueError("输出尺寸必须是 1–2048 的整数宽高。")
    return tuple(value)


def _open(data):
    if not isinstance(data, (bytes, bytearray)) or not 0 < len(data) <= MAX_SOURCE_BYTES:
        raise ValueError("图片为空或超过 64 MiB，请先压缩源图片。")
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(BytesIO(data)) as source:
                if source.width * source.height > MAX_SOURCE_PIXELS:
                    raise ValueError("源图片超过 6400 万像素，请先缩小后导入。")
                if getattr(source, "n_frames", 1) != 1:
                    raise ValueError("请导入单帧图片；动画素材需要先选择并导出一帧。")
                original_format = source.format
                source.load()
                oriented = ImageOps.exif_transpose(source)
                result = oriented.convert("RGBA")
                if oriented is not source:
                    oriented.close()
                return result, original_format
    except (UnidentifiedImageError, Image.DecompressionBombWarning, Image.DecompressionBombError,
            OSError, SyntaxError) as error:
        raise ValueError("无法安全解码图片，请使用完整的 PNG 或 JPEG 图片。") from error


def _box(image, box):
    if box is None:
        return image.copy()
    if (not isinstance(box, (list, tuple)) or len(box) != 4
            or any(type(value) not in (int, float) or not math.isfinite(value) for value in box)):
        raise ValueError("裁剪区域必须是有限的 left/top/right/bottom 四个坐标。")
    left, top, right, bottom = box
    if not (0 <= left < right <= image.width and 0 <= top < bottom <= image.height):
        raise ValueError("裁剪区域必须完整位于转正后的原图内，且宽高大于零。")
    # Pillow rounds fractional crop boundaries. Validate the exact pixels too,
    # so a subpixel sliver cannot turn into an empty image silently.
    rectangle = tuple(round(value) for value in box)
    if rectangle[2] <= rectangle[0] or rectangle[3] <= rectangle[1]:
        raise ValueError("裁剪区域不足一个像素。")
    return image.crop(rectangle)


def _png(image, card_frame=None):
    stream = BytesIO()
    metadata=PngInfo()
    if card_frame is not None:metadata.add_text('lal.cardFrame',json.dumps(list(card_frame),separators=(',',':')))
    image.save(stream, format="PNG", optimize=True, pnginfo=metadata)
    raw = stream.getvalue()
    # Validate generated bytes with the same parser used by game installation,
    # including PNG structure, actual decoded pixels and the API output quota.
    validate_media(raw, "generated.png")
    return raw


def _fit(image, size):
    return ImageOps.fit(image, _size(size), method=Image.Resampling.LANCZOS, centering=(0.5, 0.5))


def inspect_image(data):
    image, original_format = _open(data)
    try:
        alpha = image.getchannel("A").getextrema()
        return {"format": original_format, "width": image.width, "height": image.height,
                "mode": image.mode, "has_alpha": alpha[0] < 255, "bytes": len(data),
                "oriented": True, "max_output_side": MAX_OUTPUT_SIDE}
    finally:
        image.close()


def crop_image(data, box, size):
    """Crop oriented pixels, then centre-fit the selected area to ``size``."""
    image, _ = _open(data)
    try:
        selected = _box(image, box)
        try:
            fitted = _fit(selected, size)
            try:
                return _png(fitted)
            finally:
                fitted.close()
        finally:
            selected.close()
    finally:
        image.close()


def import_image(path, crop=None, size=(320, 480), quality=5, frame=False):
    """Read a source without modifying it; optionally create a quality frame."""
    path = Path(path)
    if path.stat().st_size > MAX_SOURCE_BYTES:
        raise ValueError("图片超过 64 MiB，请先压缩源图片。")
    data = path.read_bytes()
    if frame:
        return make_card(data, quality=quality, size=size, box=crop)
    return crop_image(data, crop, size)


def _mask(data, size):
    """An RGBA cutout uses alpha; an opaque grayscale/RGB mask uses luminance."""
    image, _ = _open(data)
    try:
        alpha = image.getchannel("A")
        mask = alpha if alpha.getextrema()[0] < 255 else image.convert("L")
        if mask is not alpha:
            alpha.close()
        if mask.size != size:
            resized = mask.resize(size, Image.Resampling.LANCZOS)
            mask.close()
            return resized
        return mask
    finally:
        image.close()


def _mask_bytes(image):
    stream = BytesIO()
    image.save(stream, "PNG")
    return stream.getvalue()


@lru_cache(maxsize=5)
def _native_frame(quality):
    if type(quality) is not int or quality not in QUALITY_COLORS:
        raise ValueError("品质必须使用游戏编号 2白／3绿／4蓝／5紫／6橙。")
    try:
        manifest = json.loads((FRAME_ROOT / "manifest.json").read_text("utf-8"))
        row = manifest["qualities"][str(quality)]
        canvas = _size(row.get("canvas", manifest.get("canvas")))
        def read(key, optional=False):
            if optional and not row.get(key):
                return None
            path = (FRAME_ROOT / row[key]).resolve()
            if not path.is_relative_to(FRAME_ROOT.resolve()):
                raise ValueError("原版框资源路径不合法。")
            return path.read_bytes()
        return {"size": canvas, "frame": read("frame"), "clip": read("clip"),
                "background": read("background", True)}
    except (OSError, KeyError, TypeError, json.JSONDecodeError) as error:
        raise ValueError("原版品质框资源缺失或损坏，请使用完整发行目录。") from error


def frame_layers(quality, size=(160, 160), *, inset=0):
    """Return independent native frame/matte layers, contained without stretching.

    The PNGs retain their original shape and alpha; letterbox margins are fully
    transparent. The clip is an independent white-visible grayscale matte.
    """
    size = _size(size)
    if type(inset) not in (int, float) or not math.isfinite(inset) or not 0 <= inset <= .35:
        raise ValueError("出框留白必须在 0%～35% 之间。")
    source = _native_frame(quality)
    width, height = source["size"]
    scale = min(size[0] / width, size[1] / height) * (1-2*inset)
    fitted = (max(1, min(size[0], round(width * scale))), max(1, min(size[1], round(height * scale))))
    offset = ((size[0] - fitted[0]) // 2, (size[1] - fitted[1]) // 2)
    layers = {"bounds": (*offset, *fitted), "native_size": source["size"]}
    for key in ("frame", "background"):
        canvas = Image.new("RGBA", size)
        if source[key]:
            image, _ = _open(source[key])
            try:
                if image.size != source["size"]:
                    raise ValueError("原版框图层尺寸与模板画布不一致。")
                resized = image.resize(fitted, Image.Resampling.LANCZOS)
                canvas.alpha_composite(resized, offset)
                resized.close()
            finally:
                image.close()
        layers[key] = _png(canvas)
        canvas.close()
    matte = _mask(source["clip"], source["size"])
    canvas = Image.new("L", size)
    resized = matte.resize(fitted, Image.Resampling.LANCZOS)
    canvas.paste(resized, offset)
    layers["clip"] = _mask_bytes(canvas)
    resized.close()
    matte.close()
    canvas.close()
    return layers


def make_card(data, quality=5, size=(160, 160), box=None, *, layer_order="split",
              foreground_mask=None, content_mask=None, include_background=True, title="",
              source_selection=None, frame_inset=0, include_frame=True):
    """Composite RGBA art with the game's independent frame and editable mattes.

    Bottom to top: optional native backing, clipped art, frame, foreground art.
    A soft foreground matte mixes the two complete stacking orders in
    premultiplied alpha, so translucent source pixels are never painted twice.
    """
    size = _size(size)
    if min(size) < 48:
        raise ValueError("原版带框头像至少需要 48×48 像素。")
    if layer_order not in ("behind", "split", "front"):
        raise ValueError("图层关系必须是 behind／split／front。")
    if type(include_background) is not bool:
        raise ValueError("原版底图开关必须是布尔值。")
    if type(include_frame) is not bool:
        raise ValueError("边框开关必须是布尔值。")
    if title:
        raise ValueError("原版盾形框没有文字条；名称请填写英雄资料。")
    layers = frame_layers(quality, size, inset=frame_inset)
    image, _ = _open(data)
    resources = [image]
    try:
        left, top, width, height = layers["bounds"]
        if source_selection is not None:
            if box is None:
                box = (0, 0, *image.size)
            checked = _box(image, box)
            checked.close()
            selected_mask = _mask(source_selection, image.size)
            selected_alpha = ImageChops.multiply(image.getchannel('A'), selected_mask)
            selected = image.copy()
            selected.putalpha(selected_alpha)
            sx, sy = (box[2]-box[0])/width, (box[3]-box[1])/height
            transform = (sx, 0, box[0]-left*sx, 0, sy, box[1]-top*sy)
            # Sample the entire source, including added selections outside the
            # shield box. Cropping to the box first would discard those pixels.
            artwork = selected.transform(size, Image.Transform.AFFINE, transform,
                                         Image.Resampling.BICUBIC, fillcolor=(0, 0, 0, 0))
            resources.extend((selected_mask, selected_alpha, selected, artwork))
        else:
            selected = _box(image, box)
            fitted = _fit(selected, (width, height))
            artwork = Image.new("RGBA", size)
            artwork.alpha_composite(fitted, (left, top))
            resources.extend((selected, fitted, artwork))
        clip = _mask(content_mask if content_mask is not None else layers["clip"], size)
        resources.append(clip)
        if layer_order == "behind":
            foreground = Image.new("L", size, 0)
        elif layer_order == "front":
            foreground = Image.new("L", size, 255)
        else:
            foreground = _mask(foreground_mask, size) if foreground_mask is not None else Image.new("L", size, 0)
            if source_selection is not None:
                # Extra selected pixels outside the initial shield naturally
                # protrude in front. Erased source pixels stay absent in every layer.
                automatic = ImageChops.invert(clip)
                combined = ImageChops.lighter(foreground, automatic)
                foreground.close()
                automatic.close()
                foreground = combined
        resources.append(foreground)
        if source_selection is not None:
            clip = Image.new("L", size, 255)
            resources.append(clip)
        back = artwork.copy()
        alpha = artwork.getchannel("A")
        back_alpha = ImageChops.multiply(alpha, clip)
        back.putalpha(back_alpha)
        resources.extend((back, alpha, back_alpha))
        canvas, _ = _open(layers["background"]) if include_background else (Image.new("RGBA", size), None)
        frame, _ = _open(layers["frame"])
        if not include_frame:
            frame.paste((0, 0, 0, 0), (0, 0, *size))
        resources.extend((canvas, frame))
        above = canvas.copy()
        resources.append(above)
        canvas.alpha_composite(back)
        canvas.alpha_composite(frame)
        above.alpha_composite(frame)
        above.alpha_composite(artwork)
        extrema = foreground.getextrema()
        if extrema == (0, 0):
            return _png(canvas,layers['bounds'] if include_frame else None)
        if extrema == (255, 255):
            return _png(above,layers['bounds'] if include_frame else None)
        upper_premultiplied, lower_premultiplied = above.convert("RGBa"), canvas.convert("RGBa")
        mixed = Image.composite(upper_premultiplied, lower_premultiplied, foreground)
        result = mixed.convert("RGBA")
        resources.extend((upper_premultiplied, lower_premultiplied, mixed, result))
        return _png(result,layers['bounds'] if include_frame else None)
    finally:
        for resource in reversed(resources):
            resource.close()
